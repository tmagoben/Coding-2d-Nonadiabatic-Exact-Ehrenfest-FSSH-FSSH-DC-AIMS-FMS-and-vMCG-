def _canonical_v270(value):
    if isinstance(value, np.generic):
        return _canonical_v270(value.item())
    if isinstance(value, complex):
        return [float(value.real), float(value.imag)]
    if isinstance(value, np.ndarray):
        return _canonical_v270(value.tolist())
    if isinstance(value, dict):
        return {
            str(key): _canonical_v270(item)
            for key, item in sorted(value.items(), key=lambda pair: str(pair[0]))
        }
    if isinstance(value, (tuple, list)):
        return [_canonical_v270(item) for item in value]
    if isinstance(value, float):
        if not np.isfinite(value):
            raise ValueError("v0.27.0 canonical data cannot contain non-finite values.")
        return float(value)
    if value is None or isinstance(value, (str, int, bool)):
        return value
    raise TypeError(f"unsupported v0.27.0 canonical value: {type(value).__name__}")


def _sha256_v270(value):
    payload = json.dumps(
        _canonical_v270(value), sort_keys=True, separators=(",", ":"), ensure_ascii=True
    ).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def _complex_pairs_v270(value):
    array = np.asarray(value, dtype=complex)
    return np.stack((array.real, array.imag), axis=-1).tolist()


def _scaled_norm_v270(left, right):
    left = np.asarray(left)
    right = np.asarray(right)
    if left.shape != right.shape:
        return float("inf")
    scale = max(float(np.linalg.norm(left)), float(np.linalg.norm(right)), 1.0)
    return float(np.linalg.norm(left - right) / scale)


def symmetric_pairs_v270(ndim):
    ndim = int(ndim)
    if ndim < 1:
        raise ValueError("symmetric-matrix dimension must be positive.")
    return tuple((a, b) for a in range(ndim) for b in range(a, ndim))


def symmetric_size_v270(ndim):
    ndim = int(ndim)
    return ndim * (ndim + 1) // 2


def svec_v270(matrix):
    """Pack a real symmetric matrix in a Frobenius-orthonormal basis."""

    matrix = np.asarray(matrix, dtype=float)
    if matrix.ndim != 2 or matrix.shape[0] != matrix.shape[1]:
        raise ValueError("svec requires a square matrix.")
    if not np.all(np.isfinite(matrix)) or _scaled_norm_v270(matrix, matrix.T) > 2.0e-12:
        raise ValueError("svec requires a finite symmetric matrix.")
    values = []
    for a, b in symmetric_pairs_v270(matrix.shape[0]):
        values.append(matrix[a, b] if a == b else np.sqrt(2.0) * matrix[a, b])
    return np.asarray(values, dtype=float)


def smat_v270(vector, ndim):
    """Invert :func:`svec_v270`."""

    vector = np.asarray(vector, dtype=float)
    ndim = int(ndim)
    if vector.shape != (symmetric_size_v270(ndim),) or not np.all(np.isfinite(vector)):
        raise ValueError("symmetric vector has an invalid shape or values.")
    matrix = np.zeros((ndim, ndim), dtype=float)
    for value, (a, b) in zip(vector, symmetric_pairs_v270(ndim)):
        matrix[a, b] = matrix[b, a] = value if a == b else value / np.sqrt(2.0)
    return matrix


def symmetric_basis_v270(ndim):
    """Return matrices F_k satisfying Tr(F_k.T F_l)=delta_kl."""

    basis = []
    for index in range(symmetric_size_v270(ndim)):
        vector = np.zeros(symmetric_size_v270(ndim), dtype=float)
        vector[index] = 1.0
        basis.append(smat_v270(vector, ndim))
    return tuple(basis)


def _symmetric_eigendecomposition_v270(matrix, name):
    matrix = np.asarray(matrix, dtype=float)
    if matrix.ndim != 2 or matrix.shape[0] != matrix.shape[1]:
        raise ValueError(f"{name} must be square.")
    if not np.all(np.isfinite(matrix)) or _scaled_norm_v270(matrix, matrix.T) > 2.0e-11:
        raise ValueError(f"{name} must be finite and symmetric.")
    values, vectors = np.linalg.eigh(0.5 * (matrix + matrix.T))
    return values, vectors


def log_spd_v270(width_matrix):
    values, vectors = _symmetric_eigendecomposition_v270(width_matrix, "width matrix")
    if float(np.min(values)) <= 0.0:
        raise ValueError("width matrix must be positive definite.")
    return (vectors * np.log(values)) @ vectors.T


def exp_symmetric_v270(log_width_matrix):
    values, vectors = _symmetric_eigendecomposition_v270(log_width_matrix, "log-width matrix")
    if float(np.max(np.abs(values))) > 700.0:
        raise ValueError("log-width eigenvalue is outside floating-point range.")
    return (vectors * np.exp(values)) @ vectors.T


def exp_frechet_symmetric_v270(log_width_matrix, direction):
    """Exact Frechet derivative D exp(E)[F] for real symmetric E and F."""

    values, vectors = _symmetric_eigendecomposition_v270(log_width_matrix, "log-width matrix")
    direction = np.asarray(direction, dtype=float)
    if direction.shape != log_width_matrix.shape or _scaled_norm_v270(direction, direction.T) > 2.0e-11:
        raise ValueError("log-width direction must be a compatible symmetric matrix.")
    transformed = vectors.T @ direction @ vectors
    exp_values = np.exp(values)
    divided = np.empty((len(values), len(values)), dtype=float)
    for i in range(len(values)):
        for j in range(len(values)):
            delta = values[i] - values[j]
            if abs(delta) < 1.0e-10:
                divided[i, j] = np.exp(0.5 * (values[i] + values[j])) * (
                    1.0 + delta**2 / 24.0
                )
            else:
                divided[i, j] = exp_values[j] * np.expm1(delta) / delta
    result = vectors @ (divided * transformed) @ vectors.T
    return 0.5 * (result + result.T)


def rotate_symmetric_v270(matrix, orthogonal):
    matrix = np.asarray(matrix, dtype=float)
    orthogonal = np.asarray(orthogonal, dtype=float)
    if matrix.ndim != 2 or matrix.shape[0] != matrix.shape[1]:
        raise ValueError("matrix to rotate must be square.")
    if orthogonal.shape != matrix.shape or _scaled_norm_v270(
        orthogonal @ orthogonal.T, np.eye(matrix.shape[0])
    ) > 2.0e-11:
        raise ValueError("coordinate transformation must be orthogonal.")
    return orthogonal @ matrix @ orthogonal.T


def _zero_index_v270(ndim):
    return (0,) * int(ndim)


def _monomial_v270(ndim, axes=()):
    powers = [0] * int(ndim)
    for axis in axes:
        powers[int(axis)] += 1
    return tuple(powers)


def _poly_add_v270(*polynomials):
    result = {}
    for polynomial in polynomials:
        for powers, value in polynomial.items():
            result[powers] = result.get(powers, 0.0 + 0.0j) + complex(value)
    return {powers: value for powers, value in result.items() if abs(value) > 0.0}


def _poly_scale_v270(polynomial, scale):
    return {powers: complex(scale) * value for powers, value in polynomial.items()}


def _poly_multiply_v270(left, right):
    result = {}
    for powers_left, value_left in left.items():
        for powers_right, value_right in right.items():
            powers = tuple(a + b for a, b in zip(powers_left, powers_right))
            result[powers] = result.get(powers, 0.0 + 0.0j) + value_left * value_right
    return {powers: value for powers, value in result.items() if abs(value) > 0.0}


def _poly_conjugate_v270(polynomial):
    return {powers: np.conj(value) for powers, value in polynomial.items()}


def _linear_polynomial_v270(ndim, constant, slopes):
    slopes = np.asarray(slopes, dtype=complex)
    if slopes.shape != (ndim,):
        raise ValueError("linear polynomial slopes have an invalid shape.")
    result = {_zero_index_v270(ndim): complex(constant)}
    for axis, value in enumerate(slopes):
        if value != 0.0:
            result[_monomial_v270(ndim, (axis,))] = complex(value)
    return result


def _shifted_quadratic_v270(matrix, center):
    """Polynomial for ``(R-center).T matrix (R-center)``."""

    matrix = np.asarray(matrix, dtype=complex)
    center = np.asarray(center, dtype=float)
    ndim = len(center)
    if matrix.shape != (ndim, ndim) or _scaled_norm_v270(matrix, matrix.T) > 2.0e-11:
        raise ValueError("quadratic-form matrix must be compatible and symmetric.")
    result = {_zero_index_v270(ndim): complex(center @ matrix @ center)}
    linear = -2.0 * (matrix @ center)
    for axis, value in enumerate(linear):
        if value != 0.0:
            result[_monomial_v270(ndim, (axis,))] = complex(value)
    for a in range(ndim):
        for b in range(ndim):
            powers = _monomial_v270(ndim, (a, b))
            result[powers] = result.get(powers, 0.0 + 0.0j) + matrix[a, b]
    return {powers: value for powers, value in result.items() if abs(value) > 0.0}


def _complex_logdet_positive_stable_v270(matrix):
    """Log determinant without wrapping the summed eigenvalue phases."""

    eigenvalues = np.linalg.eigvals(np.asarray(matrix, dtype=complex))
    if not np.all(np.isfinite(eigenvalues)) or np.min(eigenvalues.real) <= 0.0:
        raise ValueError("complex Gaussian precision lacks a positive-stable spectrum.")
    return complex(np.sum(np.log(eigenvalues)))


def cross_correlated_gaussian_data_v270(
    qi, pi, width_i, chirp_i, qj, pj, width_j, chirp_j
):
    """Return exact overlap, mean, and full covariance for two packets."""

    qi = np.asarray(qi, dtype=float)
    pi = np.asarray(pi, dtype=float)
    qj = np.asarray(qj, dtype=float)
    pj = np.asarray(pj, dtype=float)
    width_i = np.asarray(width_i, dtype=float)
    chirp_i = np.asarray(chirp_i, dtype=float)
    width_j = np.asarray(width_j, dtype=float)
    chirp_j = np.asarray(chirp_j, dtype=float)
    ndim = len(qi) if qi.ndim == 1 else 0
    if ndim < 1 or any(value.shape != (ndim,) for value in (pi, qj, pj)):
        raise ValueError("cross-Gaussian centres and momenta must be equally sized vectors.")
    if any(value.shape != (ndim, ndim) for value in (width_i, chirp_i, width_j, chirp_j)):
        raise ValueError("cross-Gaussian width and chirp matrices have invalid shapes.")
    if not all(
        np.all(np.isfinite(value))
        for value in (qi, pi, width_i, chirp_i, qj, pj, width_j, chirp_j)
    ):
        raise ValueError("cross-Gaussian data must be finite.")
    wi, _ = _symmetric_eigendecomposition_v270(width_i, "bra width matrix")
    wj, _ = _symmetric_eigendecomposition_v270(width_j, "ket width matrix")
    if min(float(np.min(wi)), float(np.min(wj))) <= 0.0:
        raise ValueError("cross-Gaussian widths must be positive definite.")
    if _scaled_norm_v270(chirp_i, chirp_i.T) > 2.0e-11 or _scaled_norm_v270(
        chirp_j, chirp_j.T
    ) > 2.0e-11:
        raise ValueError("cross-Gaussian chirps must be symmetric.")
    bra_precision = width_i + 1.0j * chirp_i
    ket_precision = width_j - 1.0j * chirp_j
    combined = bra_precision + ket_precision
    linear = bra_precision @ qi + ket_precision @ qj + 1.0j * (pj - pi)
    constant = (
        -0.5 * qi @ bra_precision @ qi
        - 0.5 * qj @ ket_precision @ qj
        + 1.0j * pi @ qi
        - 1.0j * pj @ qj
    )
    covariance = np.linalg.inv(combined)
    mean = covariance @ linear
    logdet_i = float(np.sum(np.log(wi)))
    logdet_j = float(np.sum(np.log(wj)))
    logdet_combined = _complex_logdet_positive_stable_v270(combined)
    log_overlap = (
        0.25 * (logdet_i + logdet_j)
        + 0.5 * ndim * np.log(2.0)
        - 0.5 * logdet_combined
        + constant
        + 0.5 * linear @ covariance @ linear
    )
    overlap = complex(np.exp(log_overlap))
    if not np.isfinite(overlap) or not np.all(np.isfinite(mean)) or not np.all(np.isfinite(covariance)):
        raise ValueError("correlated cross-Gaussian moments are non-finite.")
    return overlap, mean, covariance


def correlated_moment_table_v270(overlap, mean, covariance, maximum_degree=4):
    """Generate all raw multivariate moments up to ``maximum_degree``."""

    mean = np.asarray(mean, dtype=complex)
    covariance = np.asarray(covariance, dtype=complex)
    ndim = len(mean) if mean.ndim == 1 else 0
    if ndim < 1 or covariance.shape != (ndim, ndim):
        raise ValueError("complex-normal moment parameters have invalid shapes.")
    if not isinstance(maximum_degree, (int, np.integer)) or isinstance(
        maximum_degree, (bool, np.bool_)
    ) or int(maximum_degree) < 0:
        raise ValueError("maximum moment degree must be a nonnegative integer.")
    cache = {_zero_index_v270(ndim): 1.0 + 0.0j}

    def moment(powers):
        powers = tuple(int(value) for value in powers)
        if powers in cache:
            return cache[powers]
        axis = next(index for index, value in enumerate(powers) if value > 0)
        reduced = list(powers)
        reduced[axis] -= 1
        reduced = tuple(reduced)
        value = mean[axis] * moment(reduced)
        for other, multiplicity in enumerate(reduced):
            if multiplicity:
                twice_reduced = list(reduced)
                twice_reduced[other] -= 1
                value += multiplicity * covariance[axis, other] * moment(tuple(twice_reduced))
        cache[powers] = complex(value)
        return cache[powers]

    for powers in itertools.product(range(int(maximum_degree) + 1), repeat=ndim):
        if sum(powers) <= int(maximum_degree):
            moment(powers)
    return complex(overlap), cache


def integrate_correlated_polynomial_v270(polynomial, moment_table):
    overlap, moments = moment_table
    value = 0.0 + 0.0j
    for powers, coefficient in polynomial.items():
        if powers not in moments:
            raise ValueError("polynomial degree exceeds the correlated moment table.")
        value += coefficient * overlap * moments[powers]
    return complex(value)


