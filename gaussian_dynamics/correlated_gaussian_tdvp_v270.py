@dataclass(frozen=True)
class CorrelatedGaussianSpinorStateV270:
    q: np.ndarray
    p: np.ndarray
    width_matrices: np.ndarray
    chirp_matrices: np.ndarray
    coefficients: np.ndarray
    time_au: float = 0.0

    def __post_init__(self):
        for name in ("q", "p", "width_matrices", "chirp_matrices"):
            object.__setattr__(self, name, np.asarray(getattr(self, name), dtype=float).copy())
        object.__setattr__(self, "coefficients", np.asarray(self.coefficients, dtype=complex).copy())

    @property
    def ngaussian(self):
        return int(self.q.shape[0]) if self.q.ndim == 2 else 0

    @property
    def ndim(self):
        return int(self.q.shape[1]) if self.q.ndim == 2 else 0

    @property
    def nstate(self):
        return int(self.coefficients.shape[1]) if self.coefficients.ndim == 2 else 0

    @property
    def symmetric_size(self):
        return symmetric_size_v270(self.ndim)

    @property
    def parameter_count(self):
        return (
            2 * self.ngaussian * self.nstate
            + 2 * self.ngaussian * self.ndim
            + 2 * self.ngaussian * self.symmetric_size
        )

    @property
    def log_width_matrices(self):
        if self.width_matrices.shape != (self.ngaussian, self.ndim, self.ndim):
            raise ValueError("cannot form log widths from invalid packet matrices.")
        return np.asarray([log_spd_v270(matrix) for matrix in self.width_matrices])

    @property
    def width_eigenvalues(self):
        return np.linalg.eigvalsh(self.width_matrices)

    def validate(self, *, require_normalized=False, tolerance=5.0e-10):
        tolerance = float(tolerance)
        if not np.isfinite(tolerance) or tolerance <= 0.0:
            raise ValueError("state tolerance must be finite and positive.")
        if self.q.ndim != 2 or self.ngaussian < 1 or self.ndim < 1:
            raise ValueError("q must have shape (ngaussian,ndim) with positive dimensions.")
        if self.p.shape != self.q.shape:
            raise ValueError("q and p must have identical shapes.")
        expected_matrix_shape = (self.ngaussian, self.ndim, self.ndim)
        if self.width_matrices.shape != expected_matrix_shape or self.chirp_matrices.shape != expected_matrix_shape:
            raise ValueError("width and chirp arrays must have shape (ngaussian,ndim,ndim).")
        if self.coefficients.ndim != 2 or self.coefficients.shape[0] != self.ngaussian or self.nstate < 1:
            raise ValueError("coefficients must have shape (ngaussian,nstate).")
        if not all(
            np.all(np.isfinite(value))
            for value in (self.q, self.p, self.width_matrices, self.chirp_matrices, self.coefficients)
        ):
            raise ValueError("correlated Gaussian state contains non-finite values.")
        for width, chirp in zip(self.width_matrices, self.chirp_matrices):
            eigenvalues, _ = _symmetric_eigendecomposition_v270(width, "width matrix")
            if float(np.min(eigenvalues)) <= 0.0:
                raise ValueError("every width matrix must be positive definite.")
            _symmetric_eigendecomposition_v270(chirp, "chirp matrix")
        if not np.isfinite(float(self.time_au)):
            raise ValueError("state time must be finite.")
        norm = self.generalized_norm
        if not np.isfinite(norm) or norm <= 0.0:
            raise ValueError("correlated Gaussian state must have positive norm.")
        if require_normalized and abs(norm - 1.0) > tolerance:
            raise ValueError("correlated Gaussian state is not normalized.")
        return self

    def nuclear_overlap_matrix(self):
        if self.q.ndim != 2:
            raise ValueError("cannot build overlap from invalid packet arrays.")
        overlap = np.zeros((self.ngaussian, self.ngaussian), dtype=complex)
        for i in range(self.ngaussian):
            overlap[i, i] = 1.0 + 0.0j
            for j in range(i + 1, self.ngaussian):
                value = cross_correlated_gaussian_data_v270(
                    self.q[i], self.p[i], self.width_matrices[i], self.chirp_matrices[i],
                    self.q[j], self.p[j], self.width_matrices[j], self.chirp_matrices[j],
                )[0]
                overlap[i, j] = value
                overlap[j, i] = np.conj(value)
        return overlap

    @property
    def generalized_norm(self):
        if self.coefficients.ndim != 2 or self.q.ndim != 2:
            return float("nan")
        overlap = self.nuclear_overlap_matrix()
        value = np.einsum(
            "ia,ij,ja->", self.coefficients.conj(), overlap, self.coefficients, optimize=True
        )
        if abs(float(np.imag(value))) > 3.0e-10:
            return float("nan")
        return float(np.real(value))

    def normalized(self):
        self.validate(require_normalized=False)
        return CorrelatedGaussianSpinorStateV270(
            self.q, self.p, self.width_matrices, self.chirp_matrices,
            self.coefficients / np.sqrt(self.generalized_norm), self.time_au,
        ).validate(require_normalized=True)

    def permuted(self, order):
        self.validate(require_normalized=False)
        order = np.asarray(order, dtype=int)
        if order.shape != (self.ngaussian,) or sorted(order.tolist()) != list(range(self.ngaussian)):
            raise ValueError("packet permutation is invalid.")
        return CorrelatedGaussianSpinorStateV270(
            self.q[order], self.p[order], self.width_matrices[order], self.chirp_matrices[order],
            self.coefficients[order], self.time_au,
        ).validate(require_normalized=False)

    def gauge_transformed(self, unitary):
        self.validate(require_normalized=False)
        unitary = np.asarray(unitary, dtype=complex)
        if unitary.shape != (self.nstate, self.nstate) or _scaled_norm_v270(
            unitary.conj().T @ unitary, np.eye(self.nstate)
        ) > 2.0e-11:
            raise ValueError("electronic gauge transformation must be unitary.")
        return CorrelatedGaussianSpinorStateV270(
            self.q, self.p, self.width_matrices, self.chirp_matrices,
            self.coefficients @ unitary.conj(), self.time_au,
        ).validate(require_normalized=False)

    def coordinate_rotated(self, orthogonal):
        self.validate(require_normalized=False)
        orthogonal = np.asarray(orthogonal, dtype=float)
        if orthogonal.shape != (self.ndim, self.ndim) or _scaled_norm_v270(
            orthogonal @ orthogonal.T, np.eye(self.ndim)
        ) > 2.0e-11:
            raise ValueError("coordinate transformation must be orthogonal.")
        return CorrelatedGaussianSpinorStateV270(
            self.q @ orthogonal.T,
            self.p @ orthogonal.T,
            np.asarray([rotate_symmetric_v270(matrix, orthogonal) for matrix in self.width_matrices]),
            np.asarray([rotate_symmetric_v270(matrix, orthogonal) for matrix in self.chirp_matrices]),
            self.coefficients,
            self.time_au,
        ).validate(require_normalized=False)

    @classmethod
    def from_diagonal_v260(cls, state):
        state = state.validate(require_normalized=False)
        return cls(
            state.q,
            state.p,
            np.asarray([np.diag(row) for row in state.widths]),
            np.asarray([np.diag(row) for row in state.chirps]),
            state.coefficients,
            state.time_au,
        ).validate(require_normalized=False)

    def to_diagonal_v260(self, *, tolerance=2.0e-11):
        self.validate(require_normalized=False)
        diagonal_widths = np.asarray([np.diag(matrix) for matrix in self.width_matrices])
        diagonal_chirps = np.asarray([np.diag(matrix) for matrix in self.chirp_matrices])
        width_offdiag = self.width_matrices - np.asarray([np.diag(row) for row in diagonal_widths])
        chirp_offdiag = self.chirp_matrices - np.asarray([np.diag(row) for row in diagonal_chirps])
        if max(float(np.max(np.abs(width_offdiag))), float(np.max(np.abs(chirp_offdiag)))) > tolerance:
            raise ValueError("correlated state cannot be represented by the diagonal v0.26.0 manifold.")
        return DiagonalGaussianSpinorStateV260(
            self.q, self.p, diagonal_widths, diagonal_chirps, self.coefficients, self.time_au
        ).validate(require_normalized=False)

    def as_dict(self):
        self.validate(require_normalized=False)
        return {
            "q": self.q.tolist(),
            "p": self.p.tolist(),
            "width_matrices": self.width_matrices.tolist(),
            "log_width_matrices": self.log_width_matrices.tolist(),
            "chirp_matrices": self.chirp_matrices.tolist(),
            "coefficients": _complex_pairs_v270(self.coefficients),
            "time_au": float(self.time_au),
            "ngaussian": self.ngaussian,
            "ndim": self.ndim,
            "nstate": self.nstate,
            "parameter_count": self.parameter_count,
            "generalized_norm": self.generalized_norm,
        }


def pack_correlated_parameters_v270(state):
    state = state.validate(require_normalized=False)
    return np.concatenate(
        (
            state.coefficients.real.reshape(-1),
            state.coefficients.imag.reshape(-1),
            state.q.reshape(-1),
            state.p.reshape(-1),
            np.concatenate([svec_v270(matrix) for matrix in state.log_width_matrices]),
            np.concatenate([svec_v270(matrix) for matrix in state.chirp_matrices]),
        )
    )


def state_from_correlated_parameters_v270(parameters, *, ngaussian, ndim, nstate, time_au):
    parameters = np.asarray(parameters, dtype=float)
    counts = (ngaussian, ndim, nstate)
    if any(
        isinstance(value, (bool, np.bool_))
        or not isinstance(value, (int, np.integer))
        or int(value) < 1
        for value in counts
    ):
        raise ValueError("ngaussian, ndim, and nstate must be positive integers.")
    ngaussian, ndim, nstate = map(int, counts)
    coefficient_count = ngaussian * nstate
    vector_count = ngaussian * ndim
    matrix_count = ngaussian * symmetric_size_v270(ndim)
    expected = 2 * coefficient_count + 2 * vector_count + 2 * matrix_count
    if parameters.shape != (expected,) or not np.all(np.isfinite(parameters)):
        raise ValueError("correlated parameter vector has an invalid shape or values.")
    coefficients = (
        parameters[:coefficient_count]
        + 1.0j * parameters[coefficient_count : 2 * coefficient_count]
    ).reshape(ngaussian, nstate)
    cursor = 2 * coefficient_count
    q = parameters[cursor : cursor + vector_count].reshape(ngaussian, ndim)
    cursor += vector_count
    p = parameters[cursor : cursor + vector_count].reshape(ngaussian, ndim)
    cursor += vector_count
    log_width_vectors = parameters[cursor : cursor + matrix_count].reshape(
        ngaussian, symmetric_size_v270(ndim)
    )
    cursor += matrix_count
    chirp_vectors = parameters[cursor : cursor + matrix_count].reshape(
        ngaussian, symmetric_size_v270(ndim)
    )
    log_widths = np.asarray([smat_v270(row, ndim) for row in log_width_vectors])
    width_matrices = np.asarray([exp_symmetric_v270(matrix) for matrix in log_widths])
    chirp_matrices = np.asarray([smat_v270(row, ndim) for row in chirp_vectors])
    return CorrelatedGaussianSpinorStateV270(
        q, p, width_matrices, chirp_matrices, coefficients, float(time_au)
    ).validate(require_normalized=False)


def _validate_correlated_domain_v270(state, settings):
    state = state.validate(require_normalized=False)
    settings = settings.validate()
    eigenvalues = state.width_eigenvalues
    if float(np.min(eigenvalues)) < float(settings.minimum_width_eigenvalue):
        raise ValueError("a Gaussian width eigenvalue fell below the configured minimum.")
    if float(np.max(eigenvalues)) > float(settings.maximum_width_eigenvalue):
        raise ValueError("a Gaussian width eigenvalue exceeded the configured maximum.")
    chirp_radius = max(
        float(np.max(np.abs(np.linalg.eigvalsh(matrix))))
        for matrix in state.chirp_matrices
    )
    if chirp_radius > float(settings.maximum_chirp_spectral_radius):
        raise ValueError("a Gaussian chirp spectral radius exceeded its configured maximum.")
    return state


def _kinetic_polynomial_correlated_v270(q, p, width, chirp, inverse_mass):
    q = np.asarray(q, dtype=float)
    p = np.asarray(p, dtype=float)
    width = np.asarray(width, dtype=float)
    chirp = np.asarray(chirp, dtype=float)
    inverse_mass = np.asarray(inverse_mass, dtype=float)
    ndim = len(q)
    if p.shape != (ndim,) or any(
        matrix.shape != (ndim, ndim) for matrix in (width, chirp, inverse_mass)
    ):
        raise ValueError("correlated kinetic polynomial dimensions differ.")
    precision = width - 1.0j * chirp
    factors = [
        _linear_polynomial_v270(
            ndim,
            (precision @ q)[axis] + 1.0j * p[axis],
            -precision[axis],
        )
        for axis in range(ndim)
    ]
    polynomial = {}
    zero = _zero_index_v270(ndim)
    for a in range(ndim):
        for b in range(ndim):
            second_derivative = _poly_add_v270(
                _poly_multiply_v270(factors[a], factors[b]),
                {zero: -precision[a, b]},
            )
            polynomial = _poly_add_v270(
                polynomial,
                _poly_scale_v270(second_derivative, -0.5 * inverse_mass[a, b]),
            )
    return polynomial


def _operator_polynomials_correlated_v270(state, model, packet):
    """Polynomial matrix for ``H g_packet`` in the fixed diabatic frame."""

    ndim = state.ndim
    nstate = state.nstate
    zero = _zero_index_v270(ndim)
    result = [[{} for _ in range(nstate)] for _ in range(nstate)]
    for output in range(nstate):
        for input_state in range(nstate):
            polynomial = {zero: model.H0[output, input_state]}
            for axis in range(ndim):
                polynomial = _poly_add_v270(
                    polynomial,
                    {_monomial_v270(ndim, (axis,)): model.H1[axis, output, input_state]},
                )
            for axis_a in range(ndim):
                for axis_b in range(ndim):
                    polynomial = _poly_add_v270(
                        polynomial,
                        {
                            _monomial_v270(ndim, (axis_a, axis_b)):
                            model.H2[axis_a, axis_b, output, input_state]
                        },
                    )
            result[output][input_state] = polynomial
    kinetic = _kinetic_polynomial_correlated_v270(
        state.q[packet], state.p[packet], state.width_matrices[packet],
        state.chirp_matrices[packet], model.inverse_mass_matrix_au,
    )
    for electronic in range(nstate):
        result[electronic][electronic] = _poly_add_v270(
            result[electronic][electronic], kinetic
        )
    return result


def build_correlated_gaussian_matrices_v270(state, model):
    state = state.validate(require_normalized=False)
    model = model.validate()
    if state.ndim != model.ndim or state.nstate != model.nstate:
        raise ValueError("state dimensions differ from the Hamiltonian model.")
    dimension = state.ngaussian * state.nstate
    overlap = np.zeros((dimension, dimension), dtype=complex)
    hamiltonian = np.zeros((dimension, dimension), dtype=complex)
    identity = np.eye(state.nstate, dtype=complex)
    for i in range(state.ngaussian):
        si = slice(i * state.nstate, (i + 1) * state.nstate)
        for j in range(state.ngaussian):
            sj = slice(j * state.nstate, (j + 1) * state.nstate)
            data = cross_correlated_gaussian_data_v270(
                state.q[i], state.p[i], state.width_matrices[i], state.chirp_matrices[i],
                state.q[j], state.p[j], state.width_matrices[j], state.chirp_matrices[j],
            )
            table = correlated_moment_table_v270(*data, maximum_degree=2)
            overlap[si, sj] = data[0] * identity
            operator = _operator_polynomials_correlated_v270(state, model, j)
            for output in range(state.nstate):
                for input_state in range(state.nstate):
                    hamiltonian[si.start + output, sj.start + input_state] = (
                        integrate_correlated_polynomial_v270(
                            operator[output][input_state], table
                        )
                    )
    if _scaled_norm_v270(overlap, overlap.conj().T) > 4.0e-10:
        raise ValueError("correlated overlap matrix is not Hermitian.")
    if _scaled_norm_v270(hamiltonian, hamiltonian.conj().T) > 4.0e-10:
        raise ValueError("correlated Hamiltonian matrix is not Hermitian.")
    return overlap, hamiltonian


def correlated_variational_energy_v270(state, model):
    state = state.validate(require_normalized=False)
    overlap, hamiltonian = build_correlated_gaussian_matrices_v270(state, model)
    coefficients = state.coefficients.reshape(-1)
    norm = float(np.real(np.vdot(coefficients, overlap @ coefficients)))
    if norm <= 0.0:
        raise ValueError("cannot evaluate the energy of a zero-norm state.")
    value = np.vdot(coefficients, hamiltonian @ coefficients) / norm
    if abs(float(np.imag(value))) > 4.0e-10:
        raise ValueError("correlated variational energy has a non-negligible imaginary part.")
    return float(np.real(value))


def correlated_reduced_density_v270(state, *, normalize=True):
    state = state.validate(require_normalized=False)
    overlap = state.nuclear_overlap_matrix()
    density = state.coefficients.T @ overlap.T @ state.coefficients.conj()
    density = 0.5 * (density + density.conj().T)
    trace = float(np.real(np.trace(density)))
    if normalize:
        if trace <= 0.0:
            raise ValueError("cannot normalize a nonpositive reduced density.")
        density = density / trace
    return density


def _tangent_terms_correlated_v270(state):
    """Return ``(packet,electronic vector,coordinate polynomial)`` in pack order."""

    state = state.validate(require_normalized=False)
    terms = []
    zero = _zero_index_v270(state.ndim)
    for packet in range(state.ngaussian):
        for electronic in range(state.nstate):
            vector = np.zeros(state.nstate, dtype=complex)
            vector[electronic] = 1.0
            terms.append((packet, vector, {zero: 1.0 + 0.0j}))
    for packet in range(state.ngaussian):
        for electronic in range(state.nstate):
            vector = np.zeros(state.nstate, dtype=complex)
            vector[electronic] = 1.0j
            terms.append((packet, vector, {zero: 1.0 + 0.0j}))
    for packet in range(state.ngaussian):
        precision = state.width_matrices[packet] - 1.0j * state.chirp_matrices[packet]
        for axis in range(state.ndim):
            terms.append(
                (
                    packet,
                    state.coefficients[packet],
                    _linear_polynomial_v270(
                        state.ndim,
                        -(precision @ state.q[packet])[axis] - 1.0j * state.p[packet, axis],
                        precision[axis],
                    ),
                )
            )
    for packet in range(state.ngaussian):
        for axis in range(state.ndim):
            slopes = np.zeros(state.ndim, dtype=complex)
            slopes[axis] = 1.0j
            terms.append(
                (
                    packet,
                    state.coefficients[packet],
                    _linear_polynomial_v270(
                        state.ndim, -1.0j * state.q[packet, axis], slopes
                    ),
                )
            )
    basis = symmetric_basis_v270(state.ndim)
    for packet in range(state.ngaussian):
        width = state.width_matrices[packet]
        inverse_width = np.linalg.inv(width)
        log_width = state.log_width_matrices[packet]
        for direction in basis:
            dwidth = exp_frechet_symmetric_v270(log_width, direction)
            normalization = 0.25 * np.trace(inverse_width @ dwidth)
            terms.append(
                (
                    packet,
                    state.coefficients[packet],
                    _poly_add_v270(
                        {zero: normalization},
                        _poly_scale_v270(
                            _shifted_quadratic_v270(dwidth, state.q[packet]), -0.5
                        ),
                    ),
                )
            )
    for packet in range(state.ngaussian):
        for direction in basis:
            terms.append(
                (
                    packet,
                    state.coefficients[packet],
                    _poly_scale_v270(
                        _shifted_quadratic_v270(direction, state.q[packet]), 0.5j
                    ),
                )
            )
    if len(terms) != state.parameter_count:
        raise AssertionError("correlated tangent count disagrees with parameter layout.")
    return terms


def active_correlated_parameter_indices_v270(state, active_shape_mask):
    state = state.validate(require_normalized=False)
    mask = np.asarray(active_shape_mask, dtype=bool)
    if mask.shape != (state.ngaussian,):
        raise ValueError("active shape mask must contain one value per packet.")
    coefficient_count = 2 * state.ngaussian * state.nstate
    indices = list(range(coefficient_count))
    cursor = coefficient_count
    for family_size in (state.ndim, state.ndim, state.symmetric_size, state.symmetric_size):
        for packet in range(state.ngaussian):
            if mask[packet]:
                start = cursor + packet * family_size
                indices.extend(range(start, start + family_size))
        cursor += state.ngaussian * family_size
    return np.asarray(indices, dtype=int)


@dataclass(frozen=True)
class CorrelatedMetricSystemV270:
    metric: np.ndarray
    rhs: np.ndarray
    velocity: np.ndarray
    active_parameter_indices: np.ndarray
    active_shape_mask: np.ndarray
    solve_receipt: MetricSolveReceiptV251
    generalized_norm: float
    energy_hartree: float
    settings: CorrelatedVariationalSettingsV270

    def __post_init__(self):
        for name in ("metric", "rhs", "velocity"):
            object.__setattr__(self, name, np.asarray(getattr(self, name), dtype=float).copy())
        object.__setattr__(
            self, "active_parameter_indices", np.asarray(self.active_parameter_indices, dtype=int).copy()
        )
        object.__setattr__(
            self, "active_shape_mask", np.asarray(self.active_shape_mask, dtype=bool).copy()
        )

    def validate(self):
        settings = self.settings.validate()
        if self.metric.ndim != 2 or self.metric.shape[0] != self.metric.shape[1]:
            raise ValueError("stored correlated metric must be square.")
        active_count = self.metric.shape[0]
        if self.rhs.shape != (active_count,):
            raise ValueError("stored correlated metric RHS has an incompatible shape.")
        if self.velocity.ndim != 1 or len(self.active_parameter_indices) != active_count:
            raise ValueError("stored velocity or active index map has an invalid shape.")
        if np.any(self.active_parameter_indices < 0) or np.any(
            self.active_parameter_indices >= len(self.velocity)
        ):
            raise ValueError("active parameter index lies outside the full vector.")
        if len(np.unique(self.active_parameter_indices)) != active_count:
            raise ValueError("active parameter indices contain duplicates.")
        if not all(np.all(np.isfinite(value)) for value in (self.metric, self.rhs, self.velocity)):
            raise ValueError("stored correlated metric system is non-finite.")
        expected_velocity, expected_receipt = solve_variational_metric_v251(
            self.metric, self.rhs, settings=settings
        )
        if _scaled_norm_v270(
            self.velocity[self.active_parameter_indices], expected_velocity
        ) > settings.structural_tolerance:
            raise ValueError("stored velocity disagrees with its SVD solve.")
        inactive = np.ones(len(self.velocity), dtype=bool)
        inactive[self.active_parameter_indices] = False
        if np.max(np.abs(self.velocity[inactive]), initial=0.0) > settings.structural_tolerance:
            raise ValueError("inactive correlated shape coordinates must have zero velocity.")
        if _scaled_norm_v270(
            self.solve_receipt.singular_values, expected_receipt.singular_values
        ) > settings.structural_tolerance:
            raise ValueError("stored correlated metric spectrum is inconsistent.")
        if not np.isfinite(float(self.generalized_norm)) or self.generalized_norm <= 0.0:
            raise ValueError("stored generalized norm must be positive.")
        if not np.isfinite(float(self.energy_hartree)):
            raise ValueError("stored correlated energy must be finite.")
        return self

    def as_dict(self):
        self.validate()
        return {
            "metric": self.metric.tolist(),
            "rhs": self.rhs.tolist(),
            "velocity": self.velocity.tolist(),
            "active_parameter_indices": self.active_parameter_indices.tolist(),
            "active_shape_mask": self.active_shape_mask.tolist(),
            "solve_receipt": self.solve_receipt.as_dict(),
            "generalized_norm": float(self.generalized_norm),
            "energy_hartree": float(self.energy_hartree),
            "settings": self.settings.as_dict(),
        }


def build_correlated_metric_system_v270(
    state,
    model,
    *,
    settings=CorrelatedVariationalSettingsV270(),
    active_shape_mask=None,
):
    settings = settings.validate()
    state = _validate_correlated_domain_v270(state, settings)
    model = model.validate()
    if state.ndim != model.ndim or state.nstate != model.nstate:
        raise ValueError("state dimensions differ from the Hamiltonian model.")
    if active_shape_mask is None:
        active_shape_mask = np.ones(state.ngaussian, dtype=bool)
    active_shape_mask = np.asarray(active_shape_mask, dtype=bool)
    active_indices = active_correlated_parameter_indices_v270(state, active_shape_mask)
    terms = _tangent_terms_correlated_v270(state)
    count = len(terms)
    full_metric = np.zeros((count, count), dtype=float)
    full_rhs = np.zeros(count, dtype=float)
    moment_cache = {}
    operator_cache = {}
    for i in range(state.ngaussian):
        operator_cache[i] = _operator_polynomials_correlated_v270(state, model, i)
        for j in range(state.ngaussian):
            data = cross_correlated_gaussian_data_v270(
                state.q[i], state.p[i], state.width_matrices[i], state.chirp_matrices[i],
                state.q[j], state.p[j], state.width_matrices[j], state.chirp_matrices[j],
            )
            moment_cache[(i, j)] = correlated_moment_table_v270(
                *data, maximum_degree=4
            )
    for mu, (packet_i, vector_i, polynomial_i) in enumerate(terms):
        conjugate_i = _poly_conjugate_v270(polynomial_i)
        for nu, (packet_j, vector_j, polynomial_j) in enumerate(terms):
            nuclear = integrate_correlated_polynomial_v270(
                _poly_multiply_v270(conjugate_i, polynomial_j),
                moment_cache[(packet_i, packet_j)],
            )
            full_metric[mu, nu] = float(np.real(np.vdot(vector_i, vector_j) * nuclear))
        projection = 0.0 + 0.0j
        for packet_j in range(state.ngaussian):
            operator = operator_cache[packet_j]
            for output in range(state.nstate):
                electronic_projection = np.conj(vector_i[output])
                if electronic_projection == 0.0:
                    continue
                for input_state in range(state.nstate):
                    amplitude = state.coefficients[packet_j, input_state]
                    if amplitude == 0.0:
                        continue
                    projection += (
                        electronic_projection
                        * amplitude
                        * integrate_correlated_polynomial_v270(
                            _poly_multiply_v270(
                                conjugate_i, operator[output][input_state]
                            ),
                            moment_cache[(packet_i, packet_j)],
                        )
                    )
        full_rhs[mu] = float(np.imag(projection))
    full_metric = 0.5 * (full_metric + full_metric.T)
    metric = full_metric[np.ix_(active_indices, active_indices)]
    rhs = full_rhs[active_indices]
    active_velocity, receipt = solve_variational_metric_v251(metric, rhs, settings=settings)
    velocity = np.zeros(count, dtype=float)
    velocity[active_indices] = active_velocity
    return CorrelatedMetricSystemV270(
        metric=metric,
        rhs=rhs,
        velocity=velocity,
        active_parameter_indices=active_indices,
        active_shape_mask=active_shape_mask,
        solve_receipt=receipt,
        generalized_norm=state.generalized_norm,
        energy_hartree=correlated_variational_energy_v270(state, model),
        settings=settings,
    ).validate()


