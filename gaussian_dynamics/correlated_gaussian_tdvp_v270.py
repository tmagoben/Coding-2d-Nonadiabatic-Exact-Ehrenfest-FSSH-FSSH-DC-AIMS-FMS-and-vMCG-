"""Full complex-symmetric-width multidimensional Gaussian TDVP for v0.27.0.

The normalized nuclear packets are

    g_I(R) = [det(Gamma_I)/pi**D]**(1/4)
             exp[-x_I.T (Gamma_I-i B_I) x_I/2 + i p_I.T x_I],

where ``x_I = R-q_I``, ``Gamma_I = exp(E_I)`` is real symmetric positive
definite, and ``B_I`` is real symmetric.  The log-Euclidean coordinate ``E``
guarantees positivity throughout nonlinear iteration and obeys

    E -> O E O.T,  B -> O B O.T

under every orthogonal coordinate transformation.  Symmetric matrices are
packed with an orthonormal ``svec`` convention: diagonal entries are unchanged
and off-diagonal entries are multiplied by ``sqrt(2)``.  Consequently the
matrix-coordinate transformation is itself orthogonal in parameter space.

All matrix elements and McLachlan tangent projections are analytic for the
fixed-frame quadratic Hamiltonian contract.  Correlated complex-normal moments
through total degree four are generated by a multivariate Wick recurrence.
"""

