def _canon(value):
    if isinstance(value, np.generic):
        return _canon(value.item())
    if isinstance(value, complex):
        return [float(value.real), float(value.imag)]
    if isinstance(value, np.ndarray):
        return _canon(value.tolist())
    if isinstance(value, dict):
        return {str(k): _canon(v) for k, v in sorted(value.items(), key=lambda x: str(x[0]))}
    if isinstance(value, (tuple, list)):
        return [_canon(v) for v in value]
    if isinstance(value, float):
        if not np.isfinite(value):
            raise ValueError("canonical checkpoint data must be finite")
        return float(value)
    if value is None or isinstance(value, (str, int, bool)):
        return value
    raise TypeError(type(value).__name__)


def _sha(value):
    return hashlib.sha256(json.dumps(_canon(value), sort_keys=True, separators=(",", ":")).encode()).hexdigest()


@dataclass(frozen=True)
class ConstantConnectionV292:
    """Constant anti-Hermitian connection generators D_mu."""

    generators: np.ndarray

    def __post_init__(self):
        object.__setattr__(self, "generators", np.asarray(self.generators, dtype=complex).copy())

    @property
    def ndim(self):
        return int(self.generators.shape[0]) if self.generators.ndim == 3 else 0

    @property
    def nstate(self):
        return int(self.generators.shape[1]) if self.generators.ndim == 3 else 0

    def validate(self, tolerance=2e-11):
        g = self.generators
        if g.ndim != 3 or g.shape[0] < 1 or g.shape[1] < 1 or g.shape[1] != g.shape[2]:
            raise ValueError("connection generators must have shape (ndim,nstate,nstate)")
        if not np.all(np.isfinite(g)):
            raise ValueError("connection contains non-finite values")
        for d in g:
            scale = max(float(np.linalg.norm(d)), 1.0)
            if np.linalg.norm(d + d.conj().T) / scale > tolerance:
                raise ValueError("connection generators must be anti-Hermitian")
        return self

    def wilson(self, displacement):
        self.validate()
        displacement = np.asarray(displacement, dtype=float)
        if displacement.shape != (self.ndim,) or not np.all(np.isfinite(displacement)):
            raise ValueError("Wilson displacement has wrong shape")
        a = -np.einsum("m,mab->ab", displacement, self.generators)
        return expm(a)

    def gauge_transformed(self, unitary):
        self.validate()
        u = np.asarray(unitary, dtype=complex)
        if u.shape != (self.nstate, self.nstate) or np.linalg.norm(u.conj().T @ u - np.eye(self.nstate)) > 2e-11:
            raise ValueError("gauge matrix must be unitary")
        return ConstantConnectionV292(np.asarray([u.conj().T @ d @ u for d in self.generators])).validate()


