"""Residual-driven curved basis adaptation for the v0.29.2 development checkpoint.

This module deliberately layers on top of the certified v0.27 correlated-width state.
It adds the geometry required by the retained v0.29.1 checkpoint: every Gaussian
packet carries a straight Wilson section generated by a constant anti-Hermitian
non-Abelian connection.  Spawn candidates are ranked by the *actual extra real
McLachlan tangent space* they add after projection against the complete current TDVP
Jacobian, rather than by overlap with the coefficient basis alone.

The key quantity is the Schur complement

    S_c = Re(K^† W K) - Re(J^† W K)^T M^+ Re(J^† W K),

where J is the complete current real-parameter tangent Jacobian, M=Re(J^†WJ), and K
contains both coefficient tangents [g_c L_c e_a, i g_c L_c e_a]. If r is the current TDSE
defect, the candidate's predicted instantaneous squared-defect reduction is

    Delta_c = y^T S_c^+ y,
    y = Re[K^† W r] - Re(J^† W K)^T M^+ Re[J^† W r].

All pseudoinverses are full-SVD, rank-audited, and fail closed on incompatible null
components.  Topology changes use a full-SVD projection of the complete curved
wavefunction.  This is a development checkpoint, not a public release.
"""

